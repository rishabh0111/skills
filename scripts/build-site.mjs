#!/usr/bin/env node
// Builds the sk-ask catalog and the README's skill tables from the skills on disk.
//
//   node scripts/build-site.mjs            rewrite both outputs
//   node scripts/build-site.mjs --check    exit 1 if either is stale, write nothing
//
// Outputs:
//   plugins/skills-core/skills/sk-ask/catalog.md   written whole: every skill per plugin
//   README.md   only between <!-- skills:start --> and <!-- skills:end -->
//
// Reads each SKILL.md frontmatter (name, description, disable-model-invocation).
// Skills with disable-model-invocation: true are user-run and shown as /name.
// The README block opens with the skill counts, then one table per group (### headings).
// The README's groups, "Say this" and "You get" come from scripts/readme.json; a
// skill missing from it goes in an "Other" group with the first sentence of its
// description. No dependencies. Running it twice changes nothing the second time.

import { readFileSync, writeFileSync, readdirSync, existsSync, statSync } from "node:fs";
import { join, resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const START = "<!-- skills:start -->";
const END = "<!-- skills:end -->";

const check = process.argv.slice(2).includes("--check");
const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const pluginsDir = join(root, "plugins");
const readmePath = join(root, "README.md");
const dataPath = join(root, "scripts", "readme.json");
const catalogPath = join(pluginsDir, "skills-core", "skills", "sk-ask", "catalog.md");

function fail(msg) { console.error(`build-site: ${msg}`); process.exit(2); }

function frontmatter(text, file) {
  const m = text.replace(/^﻿/, "").match(/^---\r?\n([\s\S]*?)\r?\n---/);
  if (!m) fail(`no frontmatter in ${file}`);
  const out = {};
  const lines = m[1].split(/\r?\n/);
  for (let i = 0; i < lines.length; i++) {
    const kv = lines[i].match(/^([A-Za-z0-9_-]+):\s*(.*)$/);
    if (!kv) continue;
    let [, key, val] = kv;
    if (/^[>|][-+]?$/.test(val)) {
      const block = [];
      while (i + 1 < lines.length && (/^\s+\S/.test(lines[i + 1]) || lines[i + 1].trim() === "")) block.push(lines[++i].trim());
      val = block.join(val.startsWith(">") ? " " : "\n").trim();
    } else if (val.startsWith('"') && val.endsWith('"') && val.length > 1) {
      try { val = JSON.parse(val); } catch { val = val.slice(1, -1); }
    } else if (val.startsWith("'") && val.endsWith("'") && val.length > 1) {
      val = val.slice(1, -1).replace(/''/g, "'");
    }
    out[key] = val;
  }
  return out;
}

function firstSentence(desc) {
  const s = String(desc || "").replace(/\\n/g, " ").replace(/\s+/g, " ").trim();
  const re = /^.*?(?<!\b(?:e\.g|i\.e|vs|etc|cf))[.!?](?=\s|$)/;
  const m = s.match(re);
  if (!m) return s;
  if (m[0].length >= 30) return m[0];
  const rest = s.slice(m[0].length).trim();
  const m2 = rest.match(re);
  return (m[0] + " " + (m2 ? m2[0] : rest)).trim();
}

const isDir = (p) => { try { return statSync(p).isDirectory(); } catch { return false; } };
const cell = (s) => String(s).replace(/\|/g, "\\|").replace(/\s+/g, " ").trim();
const label = (s) => `\`${s.userRun ? "/" : ""}${s.name}\``;

// ---------- data ----------

if (!isDir(pluginsDir)) fail(`no plugins directory at ${pluginsDir}`);
if (!existsSync(readmePath)) fail(`missing ${readmePath}`);
if (!isDir(dirname(catalogPath))) fail(`missing ${dirname(catalogPath)}`);

const data = existsSync(dataPath) ? JSON.parse(readFileSync(dataPath, "utf8")) : [];
if (!Array.isArray(data)) fail("scripts/readme.json must be an array");
data.forEach((d, i) => {
  for (const k of ["skill", "group", "say", "get"]) {
    if (typeof d[k] !== "string" || !d[k].trim()) fail(`scripts/readme.json entry ${i + 1}: "${k}" must be a non-empty string`);
  }
});

const plugins = readdirSync(pluginsDir)
  .filter((p) => isDir(join(pluginsDir, p, "skills")))
  .sort((a, b) => (a === "skills-core" ? -1 : b === "skills-core" ? 1 : a.localeCompare(b)))
  .map((plugin) => {
    const skillsDir = join(pluginsDir, plugin, "skills");
    const skills = readdirSync(skillsDir)
      .filter((d) => existsSync(join(skillsDir, d, "SKILL.md")))
      .map((d) => {
        const file = join(skillsDir, d, "SKILL.md");
        const fm = frontmatter(readFileSync(file, "utf8"), file);
        return { name: fm.name || d, userRun: String(fm["disable-model-invocation"]).trim() === "true", what: firstSentence(fm.description) };
      })
      .sort((a, b) => a.name.localeCompare(b.name));
    return { plugin, skills };
  })
  .filter((p) => p.skills.length);

const allSkills = plugins.flatMap((p) => p.skills);
const byName = new Map(allSkills.map((s) => [s.name, s]));
for (const d of data) if (!byName.has(d.skill)) fail(`scripts/readme.json lists "${d.skill}", which has no SKILL.md`);

// ---------- the sk-ask catalog ----------

function catalog() {
  const out = [
    "# Catalog",
    "",
    "Generated by `scripts/build-site.mjs` from `plugins/*/skills/*/SKILL.md`. Do not edit by hand; regenerate with `node scripts/build-site.mjs`.",
  ];
  for (const { plugin, skills } of plugins) {
    out.push("", `## \`${plugin}\``, "", "| Skill | How it starts | What it is for |", "|---|---|---|");
    for (const s of skills) out.push(`| ${label(s)} | ${s.userRun ? "you run it" : "on its own"} | ${cell(s.what)} |`);
  }
  return out.join("\n") + "\n";
}

// ---------- the README tables ----------

function readmeTables() {
  const groups = new Map();
  const add = (group, row) => { if (!groups.has(group)) groups.set(group, []); groups.get(group).push(row); };
  for (const d of data) add(d.group, [label(byName.get(d.skill)), d.say, d.get]);
  const listed = new Set(data.map((d) => d.skill));
  for (const s of allSkills) {
    if (listed.has(s.name)) continue;
    add("Other", [label(s), s.userRun ? `type \`/${s.name}\`` : "applies on its own", s.what.replace(/\.$/, "")]);
  }
  const run = allSkills.filter((s) => s.userRun).length;
  const out = [`${allSkills.length} skills: ${run} you run by typing their name with a slash, and ${allSkills.length - run} that apply on their own.`, ""];
  for (const [group, rows] of groups) {
    out.push(`### ${group}`, "", "| Skill | Say this | You get |", "|---|---|---|");
    for (const r of rows) out.push(`| ${r.map(cell).join(" | ")} |`);
    out.push("");
  }
  return out.join("\n");
}

// ---------- write or check ----------

const readme = readFileSync(readmePath, "utf8");
const a = readme.indexOf(START), b = readme.indexOf(END);
if (a === -1 || b === -1 || b < a) fail(`markers ${START} / ${END} not found in README.md`);
if (readme.indexOf(START, a + 1) !== -1) fail(`${START} appears more than once in README.md`);
const eol = readme.includes("\r\n") ? "\r\n" : "\n";
const inner = (eol + readmeTables()).replace(/\r?\n/g, eol);

const outputs = [
  { path: catalogPath, next: catalog() },
  { path: readmePath, next: readme.slice(0, a + START.length) + inner + readme.slice(b) },
];

const stale = [];
for (const { path, next } of outputs) {
  const before = existsSync(path) ? readFileSync(path, "utf8") : null;
  if (before === next) continue;
  stale.push(path.slice(root.length + 1).replace(/\\/g, "/"));
  if (!check) writeFileSync(path, next);
}

if (check) {
  if (stale.length) { console.error(`build-site: stale. Run: node scripts/build-site.mjs\n  ${stale.join("\n  ")}`); process.exit(1); }
  console.log(`build-site: up to date (${outputs.length} files checked).`);
} else {
  console.log(stale.length ? `build-site: wrote\n  ${stale.join("\n  ")}` : "build-site: no change.");
}
